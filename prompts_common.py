# ------------------------------------------------------------------
# 재시도(retry) 프롬프트
# 기존 build_retry_prompt에는 난이도 루브릭이 전혀 없어서, 재작성 AI가
# 애초에 난이도를 산정했던 기준을 모른 채 수정하는 문제가 있었습니다.
# 여기서는 축약된 루브릭 요약을 함께 전달합니다.
# ------------------------------------------------------------------
RUBRIC_SUMMARY_FOR_RETRY = """\
<difficulty_rubric_summary note="원본 문항이 이 기준으로 난이도가 산정되었습니다. 수정 시에도 이 배정을 유지하세요">
- A(규칙개수): 0=기본규칙1개 / 1=기본규칙2~3개 / 2=예외규칙1개 / 3=예외규칙2개이상
- B(단서위치): 0=동일절 / 1=인접절 / 2=비인접(문단 전체 탐색) / 3=단서없음·전체문맥추론
- C(오답변별력): 0=무관한오답 / 1=매력적오답1개 / 2=매력적오답2개+ / 3=고도화된함정오답
- D(지문형식): 0=무지문·단문 / 1=초단문지문(2~3문장) / 2=완성형지문(4~5문장)
</difficulty_rubric_summary>"""


def build_retry_system_prompt() -> str:
    return f"""{PERSONA}
아래 [반려된 문항 목록]의 각 문항은 검수 과정에서 결함이 발견되었습니다.
각 문항별 반려 사유를 완벽히 반영해 수정된 문항들을 다시 출력하세요.

{RUBRIC_SUMMARY_FOR_RETRY}

{CRITICAL_RULES}

<retry_rules priority="highest">
1. 문제 구성 시 각 문장(또는 보기 선지)은 Lexile 850L 이하, Longman High Beginning~Low
   Intermediate, K-5 어휘 수준, 12단어 이내로 짧고 명확하게 생성하세요. 할당받은 '문법 개념
   표현'을 위해서만 부분적으로 850L 이상을 허용합니다.
2. 각 문항의 원래 '문제 유형(발문)'과 '강제 지문 소재'는 그대로 유지하세요.
3. 출력 형식은 원본과 100% 동일한 양식([발문], [보기/지문], [정답], [해설], [난이도 산출
   내역], [플래그 내역])을 유지해야 합니다.
4. 각 문제는 반드시 원래의 문제 번호 태그(예: 【문제 1】, 【문제 3】)로 시작해야 합니다.
5. 서론이나 결론 없이 오직 수정된 문항 세트들만 순서대로 출력하세요.
</retry_rules>

※ 오답 설계 시 복수정답이 되지 않도록 유의할 것"""


def build_retry_user_prompt(failed_items, point_text: str) -> str:
    prompt = f"""<target_concept_db note="오답 설계 시 복수정답이 되지 않도록 이 DB를 재확인하세요">
{point_text}
</target_concept_db>

<rejected_items>"""
    for item in failed_items:
        prompt += f"""
==================================================
【문제 {item['q_num']}】
- 반려 사유: {item['fail_reason']}
- 원본 문항:
{item['original_text']}
==================================================
"""
    prompt += "</rejected_items>"
    return prompt
