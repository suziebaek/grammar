# prompts.py
def build_generation_prompt(ref_text, selected_major, selected_mid, selected_minor_label, point_text, qtype, num_for_this_type, extra, q_assignments, integration_rule):
    return f"""당신은 대한민국 강남권 최고 수준의 영어 내신 출제위원입니다.

=== [역할 A] 기출문제 벤치마킹 ===
아래 기출문제를 통해 발문 형식, 선지 구성 방식, 보기 스타일을 완벽하게 모방하세요.
{ref_text}

=== [역할 B] 출제 타겟 개념 ===
- 대분류: {selected_major}
- 중분류: {selected_mid}
- 소분류: {selected_minor_label}
- 핵심 출제 포인트: {point_text}

=== 출제 조건 ===
- 문제 유형: {qtype}
- 총 생성 개수: {num_for_this_type}개
- 추가 요청: {extra if extra else '없음'}

=== ★ [역할 C] 난이도 평가 척도 및 배정표 (필수 적용) ★ ===
당신은 할당된 타겟 난이도에 맞추기 위해 아래 4가지 항목(A~D)의 점수를 합산하여 문항을 설계해야 합니다. (총점 0~8점)
각 항목의 [AI 판별 신호(명시적 규칙)]을 반드시 적용하여 지정된 점수 기준에 맞게 문제를 출제하세요.

[항목별 점수 기준 및 명시적 출제 규칙]
A. 필요 문법 규칙 개수
   - [AI 판별 신호]: 정답 도출에 필요한 별개 문법 규칙을 모두 나열하고 개수를 카운트하여 설계합니다. (*같은 문법 범주의 하위 규칙은 1개로 카운트. 예: 수동태의 형태와 시제는 '수동태' 1개로 카운트)
   - 0점: 1개 / 1점: 2개 / 2점: 3개 이상

B. 단서 위치
   - [AI 판별 신호]: 정답을 결정하는 단서(키워드/시제 신호어 등)가 문항 내 어디에 위치할지 의도적으로 배치합니다. (*단서가 의미적 맥락으로만 존재할 경우, 정답 결정에 필요한 정보가 담긴 가장 먼 절의 위치 기준)
   - 0점: 빈칸과 같은 절(clause) 내 / 1점: 빈칸과 다른 절(인접 문장) / 2점: 문단 전체를 읽어야 단서 확인 가능

C. 오답 변별력
   - [AI 판별 신호]: 각 오답 선지가 "정답 규칙의 변형(시제/형태 오류)"인지 "전혀 무관한 규칙"인지 명확히 분류하여 선지를 구성합니다.
   - 0점: 오답 전부 무관한 규칙 (소거 쉬움)
   - 1점: 오답 중 정답과 같은 규칙의 변형이 1개 있음
   - 2점: 정답과 같은 규칙의 변형 오답이 2개 이상이거나, 정답보다 더 그럴듯해 보이는 오답(학생의 흔한 오개념으로 설명 가능한 오답)이 1개 이상 있음.

D. 예외성
   - [AI 판별 신호]: 출제하는 규칙이 교재 내 "기본 규칙"인지, "예외/불규칙"인지 매칭하여 출제합니다.
   - 0점: 기본 규칙 1개만 매칭 / 1점: 기본 규칙 + 예외 규칙 1개 매칭 / 2점: 예외 규칙만 매칭, 또는 예외의 예외

=== ★ [역할 D] 문항별 난이도 배정표 (명령) ★ ===
반드시 아래 지정된 번호와 난이도 타겟(점수 구간) 및 [상세 조건]에 맞춰서 정확히 {num_for_this_type}문제를 창작하세요.
각 문항 옆에 부여된 A, B, C, D 상세 조건을 100% 그대로 적용하여 문제를 설계하세요.
{q_assignments}

=== ★ 출제 규칙 (엄격 준수) ===
1. [지문 창작]: 기출의 문장 뼈대는 모방하되, 주어/어휘/상황을 완전히 새로운 내용으로 창작하세요. 
2. [지문 길이 및 Lexile]: 문제 생성에 필요한 문장 생성 시, 각 문장은 Lexile 800L 수준에 10단어 미만 길이로 생성하세요. 할당받은 '문법 개념 표현'을 위해서만 800L 이상의 문장을 허용합니다. 지문을 생성하는 문제의 경우, 최대 5문장까지만 생성하세요.
3. [소재의 다양성 강제]: 각 문항의 지문 소재는 반드시 서로 완전히 다른 분야(예: 역사, 생물학, 예술, 경제, 심리학 등)에서 골고루 출제하세요. 한 세트 내에서 유사한 소재가 반복되는 것을 엄격히 금지합니다.
4. [치명적 오답 금지]: 'cans', 'musted' 같이 존재하지 않는 유치한 단어를 지어내는 것을 엄격히 금지합니다.
5. [고품질 오답 설계]: 항목 C(오답 변별력)의 점수를 충족하기 위해, 단순히 단어의 형태만 바꾸는 것을 넘어 '주어와 동사 사이의 거리를 멀게 배치'하거나 '수식어를 복잡하게 중첩'시키는 등 구문 분석을 요하는 교묘한 함정을 적극 활용하세요.
6. 선지는 ①②③④⑤ 형식으로 5개 구성, 각 문제마다 [정답]과 [해설]을 포함하세요.
7. [해설 작성 규칙]: 해설에 "이 문제는 ~을 묻고 있다" 같은 출제자의 의도를 설명하는 메타적 코멘트를 절대 금지합니다. 오직 문법적 팩트에 기반하여 건조하게 작성하되, 길이를 엄격하게 제한합니다.
   - [정답 해설]: 핵심 문법 규칙만 설명하며 최대 2문장 이하로 작성하세요. 토큰 낭비를 막기 위해 정답 해설만 제공합니다.  
8. [무결성 자체 검토]: 출력하기 전, ①보기 개수와 정답 번호가 일치하는지, ②정답 번호와 해설에서 설명하는 내용이 정확히 일치하는지 스스로 점검하여 논리적 모순을 100% 제거하세요.
{integration_rule}
=== 출력 형식 (반드시 준수) ===
【문제 N】
[발문]
내용

[보기/지문]
① ...
② ...
③ ...
④ ...
⑤ ...

[정답] 

[해설]
[정답 해설]: 정답인 이유를 문법적으로 명확히 설명.
[난이도 산출 내역]: 타겟 [(상/중/하)] / 지시받은 A(점)+B(점)+C(점)+D(점) = 총 (점)점

---
"""
